package tool

import (
	"strings"
	"testing"
)

func TestDecodeCommandOutputUTF8(t *testing.T) {
	got := DecodeCommandOutput([]byte("中文 ok"))
	if got != "中文 ok" {
		t.Fatalf("DecodeCommandOutput() = %q", got)
	}
}

func TestDecodeCommandOutputGBK(t *testing.T) {
	gbk := []byte{
		0xC7, 0xFD, 0xB6, 0xAF, 0xC6, 0xF7, 0x20, 0x44, 0x20, 0xD6, 0xD0, 0xB5, 0xC4, 0xBE, 0xED, 0xCA, 0xC7, 0x20, 0x44, 0x61, 0x74, 0x61, 0x0D, 0x0A,
		0x20, 0xBE, 0xED, 0xB5, 0xC4, 0xD0, 0xF2, 0xC1, 0xD0, 0xBA, 0xC5, 0xCA, 0xC7, 0x20, 0x39, 0x41, 0x36, 0x37, 0x2D, 0x37, 0x43, 0x32, 0x33, 0x0D, 0x0A,
		0xCF, 0xB5, 0xCD, 0xB3, 0xD5, 0xD2, 0xB2, 0xBB, 0xB5, 0xBD, 0xD6, 0xB8, 0xB6, 0xA8, 0xB5, 0xC4, 0xC2, 0xB7, 0xBE, 0xB6, 0xA1, 0xA3,
	}
	got := DecodeCommandOutput(gbk)
	for _, want := range []string{
		"驱动器 D 中的卷是 Data",
		"卷的序列号是 9A67-7C23",
		"系统找不到指定的路径。",
	} {
		if !strings.Contains(got, want) {
			t.Fatalf("DecodeCommandOutput() missing %q in %q", want, got)
		}
	}
	if strings.ContainsRune(got, '\uFFFD') {
		t.Fatalf("DecodeCommandOutput() contains replacement rune: %q", got)
	}
}
